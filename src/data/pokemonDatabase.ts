const BANNED_SET = new Set(CHAMPIONS_BANNED_SPECIES);

export function isChampionsLegal(rawName: string): boolean {
  const clean = rawName.toLowerCase().trim();
  if (BANNED_SET.has(clean)) return false;
  // Prefix check for forms (e.g. ogerpon-*, urshifu-*, tornadus-*, etc.)
  for (const b of CHAMPIONS_BANNED_SPECIES) {
    if (clean === b || clean.startsWith(`${b}-`)) return false;
  }
  return true;
}

